def margins_doubled(root: object) -> bool:
    """Whether Hancom reads the margins and the line spacing a paragraph shape holds outside ``hp:switch`` as
    ``hp:default`` holds them, doubled: in a document an older Hancom saved, its ``version.xml`` giving an
    ``xmlVersion`` below 1.31."""

    element = getattr(getattr(root, "version", None), "element", None)
    value = element.get("xmlVersion") if element is not None else None
    try:
        return value is not None and float(value) < 1.31
    except ValueError:
        return False


def in_char_units(value: float, height: int) -> int:
    """A paragraph margin or spacing given in ``unit="CHAR"`` as HWPUNIT: Hancom Office 2024 counts *value*
    two-hundredths of *height*, the character size of the first paragraph style (바탕글), whatever the
    paragraph's own style or characters (80 at 10 pt lays out 400, at 15 pt 600)."""

    return int(value * height / 200)


def char_unit_height(root: Any) -> int:
    """The character size margins in ``unit="CHAR"`` count in: that of the first paragraph style (바탕글)."""

    try:
        style = root.style(0)
        run_style = root.char_property(style.char_pr_id_ref) if style is not None else None
    except Exception:  # pragma: no cover - defensive
        run_style = None
    attributes = getattr(run_style, "attributes", None) or {}
    return int(_style_number(attributes.get("height"), 1000.0))


def _margin_hwpunit(root: Any, margin: Any, name: str) -> int:
    """A paragraph shape's margin *name* (``intent``, ``left``, ...) in HWPUNIT, one in ``unit="CHAR"``
    converted (see :func:`in_char_units`)."""

    value = _style_number(getattr(margin, name, 0), 0.0)
    if (getattr(margin, "units", None) or {}).get(name) == "CHAR":
        return in_char_units(value, char_unit_height(root))
    return int(value)


def text_style_from_refs(
    document: object,
    para_pr_id_ref: object,
    char_pr_id_refs: "list[object]",
    label: str | None = None,
    end_char_pr_id_ref: object = None,
) -> TextStyle:
    """Hancom layout settings of a paragraph shape and the first resolvable
    character shape among *char_pr_id_refs*; *label*, when given, is the number
    Hancom draws before the paragraph (see :func:`paragraph_label`).
    *end_char_pr_id_ref* is the character shape of the paragraph's end (its
    last run): a bullet or number label without a character shape of its own
    takes that one, else the text's."""

    ratio, spacing, use_font_space, hangul_face, glyph_face, bold = 100.0, 0.0, False, "", "", False
    italic = False
    latin_face = symbol_face = ""
    script_size = 1.0
    script_sizes: tuple[tuple[str, float], ...] = ()
    scripts: tuple[tuple[str, float, float], ...] = ()
    root = _document_root(document)
    height, used = 1000, None
    for ref in char_pr_id_refs:
        try:
            run_style = root.char_property(ref)
        except Exception:  # pragma: no cover - defensive
            run_style = None
        if run_style is None:
            continue
        children = getattr(run_style, "child_attributes", {}) or {}
        ratios, spacings = children.get("ratio") or {}, children.get("spacing") or {}
        ratio = _style_number(ratios.get("hangul"), 100.0)
        spacing = _style_number(spacings.get("hangul"), 0.0)
        scripts = tuple(
            (name, _style_number(ratios.get(name), ratio), _style_number(spacings.get(name), spacing))
            for name in SEPARATE_SCRIPTS
            if (_style_number(ratios.get(name), ratio), _style_number(spacings.get(name), spacing)) != (ratio, spacing)
        )
        use_font_space = (getattr(run_style, "attributes", {}) or {}).get("useFontSpace") in {"1", "true"}
        bold = "bold" in children
        italic = "italic" in children
        script_size = _SUPSUB_SIZE if "supscript" in children or "subscript" in children else 1.0
        # 상대 크기 (hh:relSz) scales the glyphs as a superscript's size does, the line height left alone
        sizes = children.get("relSz") or {}
        relative = _style_number(sizes.get("hangul"), 100.0)
        script_sizes = tuple(
            (name, script_size * _style_number(sizes.get(name), relative) / 100)
            for name in SEPARATE_SCRIPTS
            if _style_number(sizes.get(name), relative) != relative
        )
        script_size *= relative / 100
        hangul_face, glyph_face = _face_names(root, ref)
        latin_face, symbol_face = _script_faces(root, ref)
        height = int(_style_number((getattr(run_style, "attributes", {}) or {}).get("height"), 1000.0))
        used = ref
        break
    try:
        prop = root.paragraph_property(para_pr_id_ref)
    except Exception:  # pragma: no cover - defensive
        prop = None
    if prop is None:
        return TextStyle(
            ratio=ratio,
            spacing=spacing,
            use_font_space=use_font_space,
            glyph_face=glyph_face,
            hangul_face=hangul_face,
            latin_face=latin_face,
            symbol_face=symbol_face,
            scripts=scripts,
            bold=bold,
            italic=italic,
            script_size=script_size,
            script_sizes=script_sizes,
        )
    breaks = getattr(prop, "break_setting", None)
    try:
        tabs = root.tab_property(getattr(prop, "tab_pr_id_ref", None))
    except Exception:  # pragma: no cover - defensive
        tabs = None
    tab_stops = tuple(sorted(
        (int(stop.pos), str(stop.type or "LEFT").upper()) for stop in getattr(tabs, "tab_stops", None) or ()))
    # hp:case carries the HWPUNIT values Hancom lays out with; hp:default doubles them.
    switch = getattr(prop, "version_switch", None)
    case = getattr(switch, "case", None) if switch is not None else None
    margin = getattr(case, "margin", None) if case is not None else None
    half = 1
    if margin is None:
        margin = getattr(prop, "margin", None)
        half = 2 if margins_doubled(root) else 1
    style = TextStyle(
        ratio=ratio,
        spacing=spacing,
        use_font_space=use_font_space,
        break_latin_word=getattr(breaks, "break_latin_word", None) or "KEEP_WORD",
        line_wrap=getattr(breaks, "line_wrap", None) or "BREAK",
        break_non_latin_word=getattr(breaks, "break_non_latin_word", None) or "BREAK_WORD",
        condense=int(_style_number(getattr(prop, "condense", 0), 0.0)),
        indent=_margin_hwpunit(root, margin, "intent") // half,
        margin_left=_margin_hwpunit(root, margin, "left") // half,
        margin_right=_margin_hwpunit(root, margin, "right") // half,
        space_before=_margin_hwpunit(root, margin, "prev") // half,
        glyph_face=glyph_face,
        hangul_face=hangul_face,
        latin_face=latin_face,
        symbol_face=symbol_face,
        scripts=scripts,
        tab_stops=tab_stops,
        auto_tab_left=bool(getattr(tabs, "auto_tab_left", False)),
        auto_tab_right=bool(getattr(tabs, "auto_tab_right", False)),
        auto_space_latin=bool(getattr(getattr(prop, "auto_spacing", None), "e_asian_eng", False)),
        auto_space_digit=bool(getattr(getattr(prop, "auto_spacing", None), "e_asian_num", False)),
        bold=bold,
        italic=italic,
        script_size=script_size,
        script_sizes=script_sizes,
    )
    heading = paragraph_label(root, para_pr_id_ref, label)
    if heading is None:
        return style
    text, head = heading
    own = head.get("charPrIDRef")
    looks, em = style, height
    if not (own and own != "4294967295" and root.char_property(own) is not None) and end_char_pr_id_ref is not None:
        own = str(end_char_pr_id_ref)  # a label without a shape of its own takes the paragraph end's
    if own and own != "4294967295" and root.char_property(own) is not None and own != used:
        looks = text_style_from_refs(document, None, [own])
        em = int(_style_number((root.char_property(own).attributes or {}).get("height"), 1000.0))
    return replace(style, head=label_room(text, head, em, looks), head_hangs=head.get("autoIndent") in {"1", "true"})


def paragraph_label(root: Any, para_pr_id_ref: object, drawn: str | None = None) -> tuple[str, dict[str, str]] | None:
    """(label, attributes of its ``hh:paraHead``) of a paragraph shape's bullet or number, or None: a bullet's
    character (a picture bullet's :data:`_PICTURE_BULLET`; None for one sized by its picture); a number's head text as Hancom measures it: when it measures the label (``useInstWidth``), the
    label it draws (*drawn*, from reading the document in order), else the text with each ``^k`` at its
    level's first number; when it does not, the text with each ``^k`` as one character of its number's width
    class."""

    try:
        prop = root.paragraph_property(para_pr_id_ref)
        header = root.headers[0].element
    except Exception:  # pragma: no cover - defensive
        return None
    heading = getattr(prop, "heading", None) if prop is not None else None
    kind = str(getattr(heading, "type", None) or "NONE").upper()
    if kind not in {"BULLET", "NUMBER", "OUTLINE"}:
        return None
    ref = str(getattr(heading, "id_ref", None) or 0)
    if kind == "BULLET":
        bullet = next((b for b in header.iter(f"{_HH}bullet") if b.get("id") == ref), None)
        paragraph_head = bullet.find(f"{_HH}paraHead") if bullet is not None else None
        if paragraph_head is None:
            return None
        if bullet.get("useImage") in {"1", "true"}:
            # a picture takes an em whatever its shape, as a character does where the label's text does not
            # give its width; where it does (useInstWidth) the picture's room was not pinned down
            if paragraph_head.get("useInstWidth") in {"1", "true"}:
                return None
            return _PICTURE_BULLET, dict(paragraph_head.attrib)
        return (bullet.get("char") or "")[:1], dict(paragraph_head.attrib)
    if kind == "OUTLINE" and ref == "0":
        section = next(iter(getattr(root, "sections", [])), None)
        sec_pr = next(section.element.iter(f"{_HP}secPr"), None) if section is not None else None
        ref = sec_pr.get("outlineShapeIDRef", "1") if sec_pr is not None else "1"
    numbering = next((n for n in header.iter(f"{_HH}numbering") if n.get("id") == ref), None)
    level = int(getattr(heading, "level", None) or 0) + 1
    heads = {int(h.get("level") or 1): h for h in numbering.iter(f"{_HH}paraHead")} if numbering is not None else {}
    paragraph_head = heads.get(level)
    if paragraph_head is None:
        return None
    attrs = dict(paragraph_head.attrib)
    measured = attrs.get("useInstWidth") in {"1", "true"}
    if measured and drawn is not None:
        return drawn, attrs

    def fill(match: "re.Match[str]") -> str:
        key = match.group(1)
        head = heads.get(level if key == "N" else int(key))
        form = (head.get("numFormat") if head is not None else None) or "DIGIT"
        if not measured:
            return "1" if form in _ASCII_NUMBER_FORMATS else "\uac00"
        from ..tools.exporter import _NUMBER_FORMATS, _number_text

        start = int(_style_number(head.get("start") if head is not None else None, 1.0))
        if key == "N":
            return f"{start}."
        # a format the text export does not write (KOREAN_DIGIT, HANGUL, ...) counts as one syllable
        return _number_text(start, form) if form in _NUMBER_FORMATS else "가"

    return re.sub(r"\^(\d+|N)", fill, paragraph_head.text or ""), attrs


def _cell_text_style(cell: object, document: object) -> TextStyle:
    """Hancom layout settings of the cell's first paragraph and first run."""

    try:
        paragraphs = list(cell.paragraphs)  # type: ignore[attr-defined]
    except Exception:  # pragma: no cover - defensive
        paragraphs = []
    if not paragraphs or document is None:
        return TextStyle()
    paragraph = paragraphs[0]
    refs = [getattr(run, "char_pr_id_ref", None) for run in getattr(paragraph, "runs", [])]
    return text_style_from_refs(document, getattr(paragraph, "para_pr_id_ref", None), refs)


def _first_run_font_pt(cell: object, document: object) -> float:
    """Resolve the cell's first run font size in points (default 10pt)."""

    try:
        paragraphs = cell.paragraphs  # type: ignore[attr-defined]
    except Exception:  # pragma: no cover - defensive
        paragraphs = []
    for paragraph in paragraphs:
        for run in getattr(paragraph, "runs", []):
            ref = getattr(run, "char_pr_id_ref", None)
            pt = _font_pt_from_ref(ref, document)
            if pt is not None:
                return pt
    return 10.0


def _font_pt_from_ref(ref: object, document: object) -> float | None:
    if ref is None or document is None:
        return None
    try:
        style = _document_root(document).char_property(ref)
    except Exception:  # pragma: no cover - defensive
        return None
    if style is None:
        return None
    height = getattr(style, "attributes", {}).get("height")
    if not height:
        return None
    try:
        return int(height) / 100.0
    except (TypeError, ValueError):  # pragma: no cover - defensive
        return None


def resolve_slot_metrics(
    cell: object,
    document: object,
    *,
    max_lines: int = 1,
    font_pt: float | None = None,
    safety: float = DEFAULT_SAFETY,
) -> SlotMetrics:
    """Build :class:`SlotMetrics` from a live table cell.

    ``available_width = max(width - margin.L - margin.R, MIN_LINE_WIDTH) * safety``, the width being the
    cell's on the table's column grid (its ``cellSz.width`` unless another row's cells push its columns' ends
    apart, see :func:`hwpx.oxml.table_sizes.grid_widths_of`),
    where the margins are the cell's effective ones (``cell.margins``: the
    table's ``hp:inMargin`` unless ``hasMargin`` is on) —
    verified against Hancom's own ``lineSeg/@horzsize`` (±10 HWPUNIT on 82% of
    cells; the safety factor covers the rest plus paragraph indent, which is left
    to the HarfBuzz pass).

    ``text_style`` carries the Hancom layout settings of the cell's first
    paragraph and run (break settings, 최소 공백, indent, 장평, 자간), so the
    fit follows Hancom's line breaking rules.

    ``available_height`` is the stored inner height, ``cellSz.height - top -
    bottom margin``: Hancom lays lines out up to it without growing the row, and
    the line pitch is Hancom's own, so no safety inset applies (the width's
    covers the error in measuring a line). A merged cell has no usable height (its
    ``cellSz.height`` is a single-row fragment, not the spanned height): it is
    recorded as *unavailable* (``None`` + ``height_unavailable``) and the fit
    stays width-only rather than guess a vertical fit. A cell stored shorter than
    one line grows with its text: Hancom draws its row as tall as the row's
    tallest cell, so that height, less the cell's own margins, is its budget
    (see :func:`_auto_grow_row_height`), and a value needing more lines than the
    row holds grows the row. A row whose laid-out lines already run past its
    stored height is as tall as those lines too (:func:`_drawn_row_height`).
    """

    slot = _cell_slot(cell, document, max_lines=max_lines, font_pt=font_pt, safety=safety)
    _left, _right, top, bottom = _effective_cell_margins(cell)
    if _row_span(cell) > 1:
        # A merged row-span's cellSz.height is only one of the spanned rows.
        return replace(slot, height_unavailable=True)
    raw_height = float(getattr(cell, "height", 0) or 0)
    stored = max(raw_height - top - bottom, 0.0) if raw_height > 0 else 0.0
    if stored * safety >= slot.line_size() * MIN_LINE_SPACING_RATIO:
        # The stored height, unless lines Hancom laid out in the row run past it:
        # Hancom then draws the row as tall as those lines.
        drawn = _drawn_row_height(cell) - top - bottom
        return replace(slot, available_height=max(stored, drawn))
    # Stored shorter than one line at the tightest pitch: the row grows with its
    # text, and holds as many lines as its tallest cell.
    return replace(slot, available_height=_auto_grow_row_height(cell, document) - top - bottom)


def _cell_slot(
    cell: object,
    document: object,
    *,
    max_lines: int,
    font_pt: float | None,
    safety: float,
) -> SlotMetrics:
    """The width, font and text style of a cell's slot, without a height budget."""

    raw_width = _grid_width(cell)
    element = getattr(cell, "element", None)
    left, right, _top, _bottom = _effective_cell_margins(cell)
    line = max(raw_width - left - right, 0.0) * safety
    inner = (max(raw_width - left - right, MIN_LINE_WIDTH) if raw_width > 0 else 0.0) * safety
    inline_width, inline_count = (
        _inline_object_width(element) if element is not None else (0.0, 0)
    )
    if inline_width:
        inner = max(inner - inline_width, 0.0)
    resolved_pt = font_pt if font_pt is not None else _first_run_font_pt(cell, document)

    return SlotMetrics(
        available_width=inner,
        font_pt=resolved_pt,
        max_lines=max(max_lines, 1),
        raw_width=raw_width,
        source="cell",
        line_spacing_ratio=_first_para_line_spacing_ratio(cell, document),
        inline_object_width=inline_width,
        inline_object_count=inline_count,
        text_style=_cell_text_style(cell, document),
        line_width=line if raw_width > 0 else None,
        min_line_width=MIN_LINE_WIDTH * safety,
        line_spacing=_first_para_line_spacing(cell, document),
        font_line=_first_para_font_line(cell, document),
    )


def _inline_object_width(cell_element: object) -> tuple[float, int]:
    """Total declared width of inline treat-as-char objects in the cell.

    Checkboxes and similar form controls flow on the text line
    (``hp:pos/@treatAsChar='1'``) and consume their ``hp:sz/@width``; a fill
    value shares whatever width remains. Objects without a declared size are
    counted but contribute 0 width (the count still signals reduced trust).
    """

    total = 0.0
    count = 0
    iter_fn = getattr(cell_element, "iter", None)
    if iter_fn is None:
        return 0.0, 0
    for node in iter_fn():
        tag = getattr(node, "tag", "")
        if not isinstance(tag, str):
            continue
        local = tag.rsplit("}", 1)[-1].lower()
        if local != "pos":
            continue
        if (node.get("treatAsChar") or "").strip() not in {"1", "true", "TRUE"}:
            continue
        holder = node.getparent() if hasattr(node, "getparent") else None
        if holder is None:
            continue
        count += 1
        for sibling in holder:
            sib_local = str(getattr(sibling, "tag", "")).rsplit("}", 1)[-1].lower()
            if sib_local == "sz":
                try:
                    total += float(sibling.get("width") or 0)
                except (TypeError, ValueError):
                    pass
                break
    return total, count


