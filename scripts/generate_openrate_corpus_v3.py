MANIFEST_SCHEMA = "hwpx.openrate.frozen-manifest.v3"
BOX_ROOT = "C:\\openrate\\v3"

#: Frozen negative controls already judged on the box in the v2 run. They are
#: referenced by box path so the oracle harness is re-validated (a control that
#: opens clean marks the whole run harness-invalid), without regenerating or
#: re-shipping corrupt bytes.
BOX_NEGATIVE_CONTROLS = (
    "C:\\openrate\\m9-full\\v1\\corrupt_section.hwpx",
    "C:\\openrate\\m9-full\\v1\\corrupt_header.hwpx",
    "C:\\openrate\\m9-full\\v1\\missing_section.hwpx",
)

#: Render-verified LaTeX samples for the equation stratum. Anything the
#: converter refuses is recorded as withheld with the typed reason — the
#: emit-rate discipline, not a silent skip.
EQUATION_LATEX_BANK = (
    r"\frac{1}{3} + \frac{2}{3} = 1",
    r"x^2 + y^2 = z^2",
    r"\sqrt{2} \times \sqrt{8} = 4",
    r"\int_{0}^{1} x^2 dx = \frac{1}{3}",
    r"\sum_{i=1}^{n} i = \frac{n(n+1)}{2}",
    r"\alpha + \beta = \gamma",
    r"a_{1} + a_{2} + a_{3}",
    r"\frac{a+b}{c-d}",
)


def _base_document(idx: int, title: str) -> HwpxDocument:
    document = HwpxDocument.new()
    document.add_paragraph(f"{cycle(ORG_BANK, idx)} {title}")
    document.add_paragraph(f"제목: {cycle(SUBJECT_BANK, idx)}")
    document.add_paragraph(f"시행일: {cycle(DATE_BANK, idx)} · 담당: {cycle(DEPT_BANK, idx)}")
    return document


def gen_baseline_regen(bucket_dir: Path) -> list[dict[str, Any]]:
    """v1's authored shapes, re-emitted by the current core serializer."""

    records: list[dict[str, Any]] = []
    for idx in range(30):
        rec_id = f"v3-baseline-{idx:03d}"
        out_path = bucket_dir / f"{rec_id}.hwpx"
        try:
            document = _base_document(idx, "일반 안내")
            if idx % 3 == 1:
                table = document.add_table(3, 3, width=42000)
                for column, value in enumerate(("구분", "내용", "비고")):
                    table.cell(0, column).text = value
                for row in (1, 2):
                    for column in range(3):
                        table.cell(row, column).text = f"항목 {row}-{column}"
            if idx % 3 == 2:
                variant = (idx // 3) % 3
                if variant == 0:
                    document.add_rectangle(14400, 7200, fill_color="#CCE5FF")
                elif variant == 1:
                    document.add_line(0, 0, 14400, 0)
                else:
                    document.add_ellipse(10000, 6000, fill_color="#FFD9CC")
            document.save_to_path(str(out_path))
            records.append(record(
                rec_id=rec_id, bucket="baseline-regen", seed=str(idx),
                output_path=out_path, produced=True,
            ))
        except Exception as exc:  # noqa: BLE001 - withheld is the honest record
            records.append(record(
                rec_id=rec_id, bucket="baseline-regen", seed=str(idx),
                output_path=None, produced=False,
                withheld_reason=f"{type(exc).__name__}: {exc}",
            ))
    return records


def gen_footnote(bucket_dir: Path) -> list[dict[str, Any]]:
    records: list[dict[str, Any]] = []
    for idx in range(15):
        rec_id = f"v3-footnote-{idx:03d}"
        out_path = bucket_dir / f"{rec_id}.hwpx"
        try:
            document = _base_document(idx, "각주 표본")
            paragraph = document.add_paragraph(f"본문 문단 {idx} — 각주가 달린 문장입니다.")
            for note_index in range(1 + idx % 3):
                document.add_footnote(
                    f"각주 {note_index + 1}: {cycle(SUBJECT_BANK, idx + note_index)}",
                    paragraph=paragraph,
                )
            if idx % 3 == 0:
                document.add_endnote(f"미주: {cycle(DEPT_BANK, idx)} 참고", paragraph=paragraph)
            document.save_to_path(str(out_path))
            records.append(record(
                rec_id=rec_id, bucket="authored-footnote", seed=str(idx),
                output_path=out_path, produced=True,
            ))
        except Exception as exc:  # noqa: BLE001
            records.append(record(
                rec_id=rec_id, bucket="authored-footnote", seed=str(idx),
                output_path=None, produced=False,
                withheld_reason=f"{type(exc).__name__}: {exc}",
            ))
    return records


