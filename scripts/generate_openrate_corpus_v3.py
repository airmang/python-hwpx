"""openrate corpus v3 — the CURRENT stack's authoring surfaces, reduced scope.

Why v3 exists
=============

The published open-rate figures were measured on a corpus *generated by* the
3.4.1-era stack (v1 frozen 2026-07, v2 additive). Fourteen tags and two majors
shipped since, and none of the authoring surfaces added in 4.x/5.x — form
fields, equations, charts, footnotes, edit plans, check boxes — exist in that
corpus. Re-running Hancom over the same frozen bytes would measure nothing
about the current serializer, so v3 regenerates with the CURRENT stack.

Reduced scope, stated rather than hidden
========================================

v3 is deliberately NOT a 497-file re-measurement. It is a ~120-file additive
tree: one small baseline stratum for comparability plus one stratum per new
authoring surface. The published metrics page must present v3 next to the
dated v1/v2 figures, never as a replacement for them. Growing the measurement
honestly beats inflating it to protect a headline.

Strata (all deterministic — fixed seeds, bank rotation, no wall clock):

* ``baseline-regen``      30  plain paragraphs / tables / dedicated shapes,
                              the v1 authored shapes re-emitted by current core
* ``authored-footnote``   15  footnotes + endnotes (5.5 render-contract repair)
* ``authored-formfield``  15  CLICKHERE create + style-preserving fill (5.1)
* ``authored-equation``   15  latex_to_eqedit over verified tokens (5.2);
                              an UnsupportedLatexError is recorded as withheld,
                              never skipped silently
* ``authored-chart``      15  office.charting XML -> core add_chart (5.3)
* ``authored-checkbox``   15  add_check_box / set_check_box round trip (5.7)
* ``edit-plan``           15  hwpx.plan.apply_edit_plan multi-op outputs (5.6)

Like v1, this runs from the automation environment: the chart stratum composes
its ChartML through ``hwpx_automation.office.charting`` (core deliberately does
not own chart composition). Everything else is pure core.

    cd python-hwpx-automation
    .venv/bin/python ../python-hwpx/scripts/generate_openrate_corpus_v3.py

Generation ONLY — no Hancom oracle here. Every produced file gets the static
``validate_editor_open_safety`` pre-filter (necessary, not sufficient); the
real verdict comes from the Windows box run. The manifest records the exact
generating stack so the measurement can never again be published without
saying what produced it.
"""
